import assert from 'node:assert/strict';
import {blankDB,makeProgram,template,workoutsForDate,applyProgramDayEdit,dateForProgramDay,markStarted,finishSession,countPeriod} from '../js/core.mjs';
const before={energy:0,pain:{knee_l:0,feet:0,back:0}};
const after={fatigue:0,exertion:0,pain:{knee_l:0,feet:0,back:0}};
// Preserve completed and missed workouts after future schedule edits.
const d=blankDB(),p=makeProgram('Finite','finite',4,'2026-11-02');
const old=template('Old','strength',[{id:'s1',exerciseId:'e1',name:'Press',sets:1,reps:10,weight:20}]);
for(const week of p.weeks)week[1]=[structuredClone(old)];
d.programs.push(p);
assert.equal(dateForProgramDay(p,1,1,'2026-11-09'),'2026-11-10');
const last=workoutsForDate(d,'2026-11-03')[0];
markStarted(d,last,before);d.sessions[last.id].sets.s1[0].done=true;
finishSession(d,last,'completed',after);
const originalId=last.id,planned=d.sessions[last.id].exercisePlans[0].weight;
const next=template('New','strength',[{id:'s2',exerciseId:'e2',name:'Bench',sets:3,reps:5,weight:80}]);
applyProgramDayEdit(d,p.id,1,1,[next],'future',[],'2026-11-09');
assert.equal(workoutsForDate(d,'2026-11-03')[0].name,'Old');
assert.equal(workoutsForDate(d,'2026-11-10')[0].name,'New');
assert.equal(workoutsForDate(d,'2026-11-17')[0].name,'New');
assert.equal(workoutsForDate(d,'2026-11-03')[0].id,originalId);
assert.equal(d.sessions[last.id].exercisePlans[0].weight,planned);
assert.equal(countPeriod(d,'2026-11-03','2026-11-03','2026-11-04').percent,100);
applyProgramDayEdit(d,p.id,2,1,[template('Week 3 ONLY')],'selected',[2],'2026-11-09');
assert.equal(workoutsForDate(d,'2026-11-17')[0].name,'Week 3 ONLY');
assert.equal(workoutsForDate(d,'2026-11-24')[0].name,'New');
assert.equal(workoutsForDate(d,'2026-11-10')[0].name,'New');
assert.throws(()=>applyProgramDayEdit(d,p.id,0,1,[next],'current',[],'2026-11-09'));
// Single occurrence override in repeating programme must not change the master.
const weekly=makeProgram('Weekly','repeat',1,'2026-11-02');weekly.weeks[0][1]=[template('Yoga')];d.programs.push(weekly);
applyProgramDayEdit(d,weekly.id,0,1,[template('Tennis ONE')],'current',[],'2026-11-09');
assert.equal(workoutsForDate(d,'2026-11-10').find(x=>x.programId===weekly.id).name,'Tennis ONE');
assert.equal(workoutsForDate(d,'2026-11-17').find(x=>x.programId===weekly.id).name,'Yoga');
assert.equal(workoutsForDate(d,'2026-11-03').find(x=>x.programId===weekly.id).name,'Yoga');
applyProgramDayEdit(d,weekly.id,0,1,[template('Running')],'future',[],'2026-11-09');
assert.equal(workoutsForDate(d,'2026-11-10').find(x=>x.programId===weekly.id).name,'Tennis ONE','date-specific override takes priority');
assert.equal(workoutsForDate(d,'2026-11-17').find(x=>x.programId===weekly.id).name,'Running');
assert.equal(workoutsForDate(d,'2026-11-03').find(x=>x.programId===weekly.id).name,'Yoga');
assert.equal(workoutsForDate(d,'2026-11-10').length,2,'overlap allowed');
console.log('PASS: schedule versions, selected/current/future, stable IDs, historical sessions, repeat rules');